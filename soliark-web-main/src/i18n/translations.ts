export const dictionaries: Record<LanguagePreference, Record<MessageKey, string>> = {
  English: en,
  Spanish: es,
  French: fr,
};

export function isLanguagePreference(value: string): value is LanguagePreference {
  return value === 'English' || value === 'Spanish' || value === 'French';
}

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}
